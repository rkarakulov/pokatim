import { openURL } from 'expo-linking';

/**
 * Внешняя ссылка (сайт организатора) — в системном браузере, не WebView: адресная строка видна, менеджер паролей и
 * сохранённые карты работают, сессия приложения сайту не доступна. Только по нажатию пользователя; адрес не
 * логируется. Ошибка (нет браузера, отказ ОС) — отклонённый промис, экран показывает баннер.
 */
export async function openExternalUrl(url: string): Promise<void> {
  await openURL(url);
}
