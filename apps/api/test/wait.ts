import { vi } from 'vitest';

/**
 * Срок ожидания условия в int-тестах (операция дошла до замка, задача захватила документ, запрос занял слот). Это не
 * проверка скорости, а опрос: условие наступает всегда, вопрос — когда. Под конкуренцией за CPU и общий `mongod`
 * (параллельные прогоны других веток) шаг доходит до замка за секунды, и прежние 1 с (умолчание `vi.waitFor`) и 5 с
 * давали ложный красный «ещё не упёрлась». Предел — меньше `testTimeout` проекта (60 с): зависшее условие
 * падает своим сообщением, а не общим таймаутом теста.
 */
export const CONDITION_WAIT = { timeout: 15_000, interval: 10 } as const;

/** `vi.waitFor` со сроком `CONDITION_WAIT`. */
export const waitUntil = <T>(callback: () => T | Promise<T>): Promise<T> =>
  vi.waitFor(callback, CONDITION_WAIT);
